import json
from pathlib import Path

from backend.app.services.llm_service import LLMService


# -----------------------------------------------------
# Paths
# -----------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[1]

RESULTS_PATH = PROJECT_ROOT / "evaluation" / "answer_results.json"
OUTPUT_PATH = PROJECT_ROOT / "evaluation" / "faithfulness_results.json"


llm_service = LLMService()


# -----------------------------------------------------
# Build evidence text
# -----------------------------------------------------

def build_evidence_text(retrieved_evidence):
    evidence_parts = []

    for agent_group in retrieved_evidence:

        agent = agent_group.get("agent", "unknown")

        for chunk in agent_group.get("chunks", []):

            evidence_parts.append(
                f"""
Agent: {agent}
Document: {chunk.get("document_type")}
Page: {chunk.get("page_number")}
Content Type: {chunk.get("content_type")}

Evidence:
{chunk.get("text", "")}
"""
            )

    return "\n".join(evidence_parts)


# -----------------------------------------------------
# Evaluate claim-level faithfulness
# -----------------------------------------------------

def evaluate_faithfulness(question, answer, evidence):

    prompt = f"""
You are evaluating the factual faithfulness of an answer
generated by a Retrieval-Augmented Generation (RAG) system.

Your task is to identify the factual claims made in the
generated answer and determine whether each claim is
supported by the retrieved evidence.

QUESTION:
{question}

GENERATED ANSWER:
{answer}

RETRIEVED EVIDENCE:
{evidence}

IMPORTANT:

Evaluate ONLY whether claims in the generated answer are
supported by the retrieved evidence.

Do NOT use outside knowledge.

Do NOT compare the answer with a reference answer.

A claim is supported only when the retrieved evidence
provides sufficient information to support that claim.

Do not penalize the answer for omitting information.

Claims containing facts, numbers, names, relationships,
comparisons, or conclusions must be supported by the
retrieved evidence.

Minor wording differences are acceptable when the meaning
is supported by the evidence.

Typographical errors that change a factual name or entity
should be treated as unsupported if the resulting claim is
factually different from the evidence.

For each factual claim, determine:

- supported = true if the evidence supports the claim
- supported = false if the evidence does not support the claim

If the answer contains no factual claims, return an empty
claims list.

Return ONLY valid JSON in exactly this format:

{{
    "claims": [
        {{
            "claim": "factual claim from the answer",
            "supported": true,
            "evidence_basis": "brief explanation of why the evidence supports the claim"
        }}
    ],
    "reason": "overall explanation"
}}

Do not include markdown.
"""


    response = llm_service.generate_judge_response(
        prompt=prompt
    )

    try:

        return json.loads(response)

    except json.JSONDecodeError:

        return {
            "claims": [],
            "reason": "Judge returned invalid JSON.",
            "raw_response": response
        }


# -----------------------------------------------------
# Calculate claim-level score
# -----------------------------------------------------

def calculate_faithfulness(claims):

    if not claims:
        return None

    supported_count = sum(
        1
        for claim in claims
        if claim.get("supported") is True
    )

    return supported_count / len(claims)


# -----------------------------------------------------
# Main
# -----------------------------------------------------

def main():

    with open(
        RESULTS_PATH,
        "r",
        encoding="utf-8"
    ) as file:

        evaluation_report = json.load(file)

    results = evaluation_report["results"]

    faithfulness_results = []

    for index, result in enumerate(
        results,
        start=1
    ):

        question_id = result["id"]

        question = result["question"]

        answer = result.get(
            "generated_answer",
            ""
        )

        retrieved_evidence = result.get(
            "retrieved_evidence",
            []
        )

        print(
            f"\nEvaluating "
            f"{index}/{len(results)}: "
            f"{question_id}"
        )

        # -------------------------------------------------
        # Handle expected abstention separately
        # -------------------------------------------------

        if result.get("abstention_expected") is True:

            print(
                "Skipping faithfulness: "
                "expected abstention."
            )

            faithfulness_results.append({

                "id": question_id,

                "question": question,

                "generated_answer": answer,

                "faithfulness_score": None,

                "claims": [],

                "reason":
                    "Expected abstention evaluated separately."
            })

            continue

        # -------------------------------------------------
        # Empty answer
        # -------------------------------------------------

        if not answer.strip():

            print(
                "Skipping: empty answer."
            )

            faithfulness_results.append({

                "id": question_id,

                "question": question,

                "generated_answer": answer,

                "faithfulness_score": None,

                "claims": [],

                "reason": "Empty answer."
            })

            continue

        # -------------------------------------------------
        # Build evidence
        # -------------------------------------------------

        evidence_text = build_evidence_text(
            retrieved_evidence
        )

        # -------------------------------------------------
        # LLM judge
        # -------------------------------------------------

        judge_result = evaluate_faithfulness(
            question=question,
            answer=answer,
            evidence=evidence_text
        )

        claims = judge_result.get(
            "claims",
            []
        )

        # -------------------------------------------------
        # Calculate score
        # -------------------------------------------------

        faithfulness_score = calculate_faithfulness(
            claims
        )

        result_data = {

            "id": question_id,

            "question": question,

            "generated_answer": answer,

            "faithfulness_score":
                faithfulness_score,

            "claims": claims,

            "reason":
                judge_result.get(
                    "reason",
                    ""
                )
        }

        faithfulness_results.append(
            result_data
        )

        print(
            "Faithfulness score:",
            faithfulness_score
        )

        print(
            "Claims:",
            len(claims)
        )

    # -----------------------------------------------------
    # Aggregate
    # -----------------------------------------------------

    valid_scores = [

        result["faithfulness_score"]

        for result in faithfulness_results

        if isinstance(
            result.get(
                "faithfulness_score"
            ),
            (int, float)
        )
    ]

    if valid_scores:

        average_faithfulness = (
            sum(valid_scores)
            / len(valid_scores)
        )

    else:

        average_faithfulness = 0.0

    # -----------------------------------------------------
    # Save
    # -----------------------------------------------------

    output = {

        "total_questions":
            len(results),

        "evaluated_questions":
            len(valid_scores),

        "average_faithfulness":
            average_faithfulness,

        "results":
            faithfulness_results
    }

    with open(
        OUTPUT_PATH,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            output,
            file,
            indent=2,
            ensure_ascii=False
        )

    # -----------------------------------------------------
    # Print
    # -----------------------------------------------------

    print(
        "\n=============================================="
    )

    print(
        "       FAITHFULNESS EVALUATION RESULTS"
    )

    print(
        "=============================================="
    )

    print(
        f"Questions evaluated: "
        f"{len(valid_scores)}"
    )

    print(
        f"Average faithfulness: "
        f"{average_faithfulness:.4f}"
    )

    print(
        f"\nDetailed results saved to:"
        f"\n{OUTPUT_PATH}"
    )

    print(
        "\n=============================================="
    )

    print(
        "     FAITHFULNESS EVALUATION COMPLETE"
    )

    print(
        "==============================================\n"
    )


if __name__ == "__main__":

    main()